export type FlatToken = { group: string; name: string; value: string };

type Flat = FlatToken[];

export const px = (value: number) => (value >= 9999 ? "9999px" : value === 0 ? "0" : `${value / 16}rem`);

/** One flat list drives every text format, so they can never disagree. */
export function flatten(tokens: DesignTokens): Flat {
  const color = (value: Oklch) => formatColor(value, tokens.meta.colorFormat);
  const list: Flat = [];

  tokens.colors.forEach((token) => {
    list.push({ group: "color", name: `color-${token.name}`, value: color(token.value) });
    token.shades.forEach((shade) =>
      list.push({ group: "color", name: `color-${token.name}-${shade.step}`, value: color(shade.value) }),
    );
  });
  tokens.semantic.forEach((role) =>
    list.push({ group: "semantic", name: `color-${role.name}`, value: color(role.value) }),
  );
  if (tokens.gradient) list.push({ group: "gradient", name: "gradient-primary", value: gradientCss(tokens.gradient) });

  const t = tokens.typography;
  if (t) {
    list.push({ group: "font", name: "font-heading", value: fontStack(t.heading.family, t.heading.category) });
    list.push({ group: "font", name: "font-body", value: fontStack(t.body.family, t.body.category) });
    list.push({ group: "font", name: "font-weight-heading", value: String(t.rhythm.headingWeight) });
    list.push({ group: "font", name: "font-weight-body", value: String(t.rhythm.bodyWeight) });
    list.push({ group: "font", name: "leading-heading", value: String(t.rhythm.headingLineHeight) });
    list.push({ group: "font", name: "leading-body", value: String(t.rhythm.bodyLineHeight) });
    list.push({ group: "font", name: "tracking-heading", value: `${t.rhythm.headingTracking}em` });
    list.push({ group: "font", name: "tracking-body", value: `${t.rhythm.bodyTracking}em` });
    t.steps.forEach((step) => list.push({ group: "text", name: `text-${step.name}`, value: step.clamp }));
  }
  tokens.spacing.forEach((step) => list.push({ group: "spacing", name: `spacing-${step.name}`, value: px(step.px) }));
  tokens.radius.forEach((step) => list.push({ group: "radius", name: `radius-${step.name}`, value: px(step.px) }));
  tokens.effects.forEach((effect) => list.push({ group: "effect", name: effect.name, value: effect.value }));
  return list;
}

export const header = (tokens: DesignTokens, comment: (text: string) => string) =>
  comment(`${tokens.meta.name} - design tokens generated by DesignHub (${siteConfig.github})`);

/** CSS custom property names can't contain a bare "." (spacing-0.5), so escape it. */
export const cssIdent = (name: string) => name.replace(/\./g, "\\.");

export function variable(tokens: DesignTokens, name: string): string {
  return `--${tokens.meta.prefix ? `${tokens.meta.prefix}-` : ""}${cssIdent(name)}`;
}

export function fontImport(tokens: DesignTokens): string {
  const t = tokens.typography;
  if (!t) return "";
  const fonts = t.heading.family === t.body.family ? [t.heading] : [t.heading, t.body];
  return `@import url("${googleFontsCssUrl(fonts)}");\n\n`;
}

/** Groups and keys shared by the YAML and Sass map exports: the flat names without their group prefix. */
export function groupedTokens(tokens: DesignTokens, prefix = ""): Map<string, Map<string, string>> {
  const groups = new Map<string, Map<string, string>>();
  flatten(tokens).forEach((token) => {
    const key = `${prefix}${token.name.replace(/^(color|gradient|font|text|spacing|radius)-/, "")}`;
    groups.set(token.group, (groups.get(token.group) ?? new Map()).set(key, token.value));
  });
  return groups;
}

/** Android resource names allow only lowercase letters, digits and underscores, and can't start with a digit. */
export function androidResource(tokens: DesignTokens, name: string): string {
  const prefix = tokens.meta.prefix ? `${tokens.meta.prefix}_` : "";
  const clean = `${prefix}${name}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
  return /^[0-9]/.test(clean) ? `c_${clean}` : clean;
}

export const androidArgb = (value: Oklch) => {
  const { r, g, b, alpha } = toRgb(value);
  return `#${[Math.round(alpha * 255), r, g, b]
    .map((channel) => channel.toString(16).padStart(2, "0"))
    .join("")
    .toUpperCase()}`;
};

/** Every color written to colors.xml, by resource name. The first token to claim a name wins. */
export function androidColorResources(tokens: DesignTokens): Map<string, Oklch> {
  const colors = new Map<string, Oklch>();
  const add = (name: string, value: Oklch) => {
    const id = androidResource(tokens, name);
    if (id && !colors.has(id)) colors.set(id, value);
  };
  tokens.colors.forEach((token) => {
    add(token.name, token.value);
    token.shades.forEach((shade) => add(`${token.name}_${shade.step}`, shade.value));
  });
  tokens.semantic.forEach((role) => add(role.name, role.value));
  return colors;
}

/** "--" is not allowed inside XML comments. */
export const xmlHeader = (tokens: DesignTokens) => header(tokens, (text) => `<!-- ${text.replace(/-{2,}/g, "-")} -->`);

/** Effects named `${kind}-${name}` (shadow-card, blur-glass) as a { name: value } scale. */
export function effectScale(tokens: DesignTokens, kind: string, prefix: string): Record<string, string> {
  return Object.fromEntries(
    tokens.effects
      .filter((effect) => effect.name.startsWith(`${kind}-`))
      .map((effect) => [`${prefix}${effect.name.slice(kind.length + 1)}`, effect.value]),
  );
}

export type Literal = string | number | Literal[] | { [key: string]: Literal };

/**
 * A value as a TypeScript literal with bare keys where they're valid, like hand-written config.
 * Objects and arrays that fit on one line (a `{ value: "#fff" }` token) stay on one line.
 */
export function tsLiteral(value: Literal, indent = ""): string {
  if (typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  const items = Array.isArray(value)
    ? value.map((item) => tsLiteral(item, inner))
    : Object.entries(value).map(([key, item]) => `${objectKey(key)}: ${tsLiteral(item, inner)}`);
  const [open, close] = Array.isArray(value) ? ["[", "]"] : ["{", "}"];
  const line = Array.isArray(value) ? `[${items.join(", ")}]` : items.length ? `{ ${items.join(", ")} }` : "{}";
  if (!line.includes("\n") && indent.length + line.length <= 80) return line;
  return `${open}\n${items.map((item) => `${inner}${item},`).join("\n")}\n${indent}${close}`;
}

/** Drops empty scales so the generated theme only lists what the tokens contain. */
export const nonEmpty = (scales: Record<string, { [key: string]: Literal }>) =>
  Object.fromEntries(Object.entries(scales).filter(([, scale]) => Object.keys(scale).length > 0));

/**
 * Base and semantic tokens in the `{ value }` shape Panda CSS and Chakra UI v3 share: colors,
 * fonts, font weights, font sizes, spacing, radii, shadows and blurs, plus semantic colors that
 * reference the base tokens (`{colors.indigo.300}`) with a `_dark` value for each role.
 */
export function presetTokens(tokens: DesignTokens) {
  const prefix = tokens.meta.prefix ? `${tokens.meta.prefix}-` : "";
  const color = (value: Oklch) => formatColor(value, tokens.meta.colorFormat);
  const scale = (entries: [string, string][]) =>
    Object.fromEntries(entries.map(([key, value]) => [`${prefix}${key}`, { value }]));
  const effect = (kind: string) =>
    Object.fromEntries(Object.entries(effectScale(tokens, kind, prefix)).map(([key, value]) => [key, { value }]));
  const t = tokens.typography;

  const colors = Object.fromEntries(
    tokens.colors.map((token): [string, Literal] => [
      `${prefix}${token.name}`,
      token.shades.length
        ? {
            DEFAULT: { value: color(token.value) },
            ...Object.fromEntries(token.shades.map((s) => [s.step, { value: color(s.value) }])),
          }
        : { value: color(token.value) },
    ]),
  );
  // Roles point at the base tokens; the synthesized white or black has no base token, so it keeps its value.
  const reference = (entry: RoleColor) =>
    entry.color
      ? `{colors.${prefix}${entry.color}${entry.step !== undefined ? `.${entry.step}` : ""}}`
      : color(entry.value);
  const semanticColors = Object.fromEntries(
    tokens.semantic.flatMap((role) => {
      const light = roleColor(tokens, role.name);
      const dark = roleColor(tokens, role.name, true);
      return light && dark
        ? [[`${prefix}${role.name}`, { value: { base: reference(light), _dark: reference(dark) } }]]
        : [];
    }),
  );

  return {
    tokens: nonEmpty({
      colors,
      fonts: scale(
        t
          ? [
              ["heading", fontStack(t.heading.family, t.heading.category)],
              ["body", fontStack(t.body.family, t.body.category)],
            ]
          : [],
      ),
      fontWeights: scale(
        t
          ? [
              ["heading", String(t.rhythm.headingWeight)],
              ["body", String(t.rhythm.bodyWeight)],
            ]
          : [],
      ),
      fontSizes: scale((t?.steps ?? []).map((step) => [step.name, step.clamp])),
      spacing: scale(tokens.spacing.map((s) => [s.name, px(s.px)])),
      radii: scale(tokens.radius.map((r) => [r.name, px(r.px)])),
      shadows: effect("shadow"),
      blurs: effect("blur"),
    }),
    ...(tokens.semantic.length ? { semanticTokens: { colors: semanticColors } } : {}),
  };
}

// A hyphen between two digits becomes an underscore, so "indigo-2-50" (indigo-2, shade 50) and
// "indigo-250" stay different keys, matching the Swift and Flutter shade ids.
export const camel = (value: string) =>
  value.replace(/(\d)-+(?=\d)/g, "$1_").replace(/-+([a-z0-9])/gi, (_, char: string) => char.toUpperCase());

export const upperFirst = (value: string) => value.charAt(0).toUpperCase() + value.slice(1);

export const objectKey = (value: string) =>
  /^[A-Za-z_$][\w$]*$/.test(value) || /^(0|[1-9]\d*)$/.test(value) ? value : JSON.stringify(value);

export const pascal = (value: string) =>
  value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

export function paletteHexes(tokens: DesignTokens): { name: string; hex: string }[] {
  return tokens.colors.map((token) => ({ name: token.name, hex: toHex(token.value) }));
}
