export const xmlText = (value: string) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** `#AARRGGBB`, the order XAML expects. */
export function xamlColor(value: Oklch): string {
  const { r, g, b, alpha } = toRgb(value);
  return `#${[Math.round(alpha * 255), r, g, b]
    .map((channel) => channel.toString(16).padStart(2, "0"))
    .join("")
    .toUpperCase()}`;
}
