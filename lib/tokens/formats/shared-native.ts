/**
 * Helpers the native and design-tool formats share: naming (`pascal`, `ident`), the color list every one of
 * them starts from (`colorEntries`), light and dark roles (`roleColor`) and the Material slots. Like the web
 * formats they read only `DesignTokens`, so every export describes the same system.
 */
export const headerText = (tokens: DesignTokens) =>
  `${tokens.meta.name} - design tokens generated by DesignHub (${siteConfig.github})`;

/** "Acme Labs" -> "AcmeLabs"; falls back to "Brand" for names without letters. */
export function pascal(name: string): string {
  const words = name.match(/[A-Za-z0-9]+/g) ?? [];
  const joined = words.map((word) => word[0]!.toUpperCase() + word.slice(1)).join("");
  return /^[A-Za-z]/.test(joined) ? joined : `Brand${joined}`;
}

/** "indigo-500" -> "indigo500", "0.5" -> "s0_5"; identifiers can't start with a digit. */
export function ident(name: string, digitPrefix: string): string {
  const parts = name
    .replace(/\./g, "_")
    .split(/[^A-Za-z0-9_]+/)
    .filter(Boolean);
  const camel = parts.map((part, i) => (i === 0 ? part : part[0]!.toUpperCase() + part.slice(1))).join("");
  return /^[0-9]/.test(camel) ? `${digitPrefix}${camel}` : camel;
}

/** Collects unique identifiers in order, dropping later duplicates. */
export function unique<T extends { id: string }>(items: T[]): T[] {
  const seen = new Set<string>();
  return items.filter((item) => (seen.has(item.id) ? false : (seen.add(item.id), true)));
}

/** `key` names the source token ("indigo", "indigo/250", "role:primary") so a format can refer back to it. */
export type ColorEntry = { id: string; key: string; value: Oklch; comment?: string };

export function colorEntries(tokens: DesignTokens, digitPrefix: string): ColorEntry[] {
  const list: ColorEntry[] = [];
  tokens.colors.forEach((color) => {
    list.push({ id: ident(color.name, digitPrefix), key: color.name, value: color.value });
    // The underscore keeps "indigo-2" shade 50 (indigo2_50) apart from "indigo" shade 250 (indigo_250).
    color.shades.forEach((shade) =>
      list.push({
        id: ident(`${color.name}_${shade.step}`, digitPrefix),
        key: `${color.name}/${shade.step}`,
        value: shade.value,
      }),
    );
  });
  tokens.semantic.forEach((role) =>
    list.push({
      id: ident(role.name, digitPrefix),
      key: `role:${role.name}`,
      value: role.value,
      comment: `semantic, ${role.ref}`,
    }),
  );
  return unique(list);
}

/**
 * Where a semantic role's color comes from in light or dark mode. `role` is the semantic role
 * that supplies it, `color` the palette color it points at (missing for the synthesized white
 * and black) and `step` the shade, when dark mode lifts the role to one.
 */
export type RoleColor = { role: string; color?: string; step?: number; value: Oklch };

/**
 * A semantic role in light or dark mode. Dark mode swaps the light background and the dark
 * foreground, and lifts every other role to its palette color's 300 (or 200) shade so it stays
 * readable on the dark background. Compose and the Panda CSS and Chakra UI exports share this.
 */
export function roleColor(tokens: DesignTokens, roleName: string, dark = false): RoleColor | undefined {
  const swap: Record<string, string> = { background: "foreground", foreground: "background" };
  const swapped = dark ? swap[roleName] : undefined;
  const item = tokens.semantic.find((entry) => entry.name === (swapped ?? roleName));
  if (!item) return undefined;
  const source = tokens.colors.find((entry) => entry.name === item.ref);
  const lift = dark && !swapped ? source : undefined;
  const shade = lift?.shades.find((s) => s.step === 300) ?? lift?.shades.find((s) => s.step === 200);
  return { role: item.name, color: source?.name, step: shade?.step, value: shade?.value ?? item.value };
}

export const px = (value: number) => (value >= 9999 ? 9999 : Math.round(value * 100) / 100);

export const weight = (value: number) => Math.min(900, Math.max(100, Math.round(value / 100) * 100));

/** `Color(0xAARRGGBB)`: the same constructor spelling in Dart and Kotlin. */
export function argbColor(value: Oklch): string {
  const { r, g, b, alpha } = toRgb(value);
  const hex = [Math.round(alpha * 255), r, g, b].map((channel) => channel.toString(16).padStart(2, "0")).join("");
  return `Color(0x${hex.toUpperCase()})`;
}

const upperFirst = (value: string) => value.charAt(0).toUpperCase() + value.slice(1);

const white: Oklch = { l: 1, c: 0, h: 0, alpha: 1 };

const black: Oklch = { l: 0, c: 0, h: 0, alpha: 1 };

/** A Material 3 color slot: `key` names its source token (see ColorEntry) or "white"/"black"; derived colors have none. */
export type MaterialSlot = { slot: string; key?: string; value: Oklch };

/** Moves `from` toward `to` by `amount` (0 to 1) in lightness and chroma, keeping the hue of `from`. */
export function mixToward(from: Oklch, to: Oklch, amount: number): Oklch {
  return {
    l: from.l + (to.l - from.l) * amount,
    c: from.c + (to.c - from.c) * amount,
    h: from.h,
    alpha: 1,
  };
}

/**
 * The Material 3 color scheme for the brand roles, shared by the Compose theme and the Android
 * themes.xml so both agree. Slots use Compose names (`primary`, `onPrimary`, `outline`, ...).
 * Outline and the containers are derived from the roles: outline sits halfway between foreground
 * and background, containers are the brand color pulled toward the background.
 */
export function materialSlots(tokens: DesignTokens, dark: boolean): MaterialSlot[] {
  const slots: MaterialSlot[] = [];
  const keyOf = (entry: RoleColor) =>
    entry.step !== undefined ? `${entry.color}/${entry.step}` : `role:${entry.role}`;
  const on = (value: Oklch) => (contrastRatio(value, white) >= contrastRatio(value, black) ? "white" : "black");
  const onSlot = (slot: string, value: Oklch) => {
    const key = on(value);
    slots.push({ slot, key, value: key === "white" ? white : black });
  };
  const background = roleColor(tokens, "background", dark);
  const foreground = roleColor(tokens, "foreground", dark);
  const brand = (slot: string, roleName: string) => {
    const entry = roleColor(tokens, roleName, dark);
    if (!entry) return;
    slots.push({ slot, key: keyOf(entry), value: entry.value });
    onSlot(`on${upperFirst(slot)}`, entry.value);
  };
  brand("primary", "primary");
  brand("secondary", "accent");
  if (background) {
    slots.push({ slot: "background", key: keyOf(background), value: background.value });
    slots.push({ slot: "surface", key: keyOf(background), value: background.value });
  }
  if (foreground) {
    slots.push({ slot: "onBackground", key: keyOf(foreground), value: foreground.value });
    slots.push({ slot: "onSurface", key: keyOf(foreground), value: foreground.value });
  }
  if (background && foreground) {
    slots.push({ slot: "outline", value: mixToward(foreground.value, background.value, 0.5) });
  }
  if (background) {
    for (const [slot, roleName] of [
      ["primary", "primary"],
      ["secondary", "accent"],
    ] as const) {
      const entry = roleColor(tokens, roleName, dark);
      if (!entry) continue;
      const container = mixToward(entry.value, background.value, dark ? 0.7 : 0.8);
      slots.push({ slot: `${slot}Container`, value: container });
      onSlot(`on${upperFirst(slot)}Container`, container);
    }
  }
  return slots;
}

