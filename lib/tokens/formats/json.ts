import { toHex } from "@/lib/color/color";
import { colorTokens } from "@/lib/color/export";
import type { DesignTokens } from "@/types/tokens";
import { defineFormat } from "@/lib/tokens/formats/define";

export function toJsonTokens(tokens: DesignTokens): string {
  const palette = tokens.colors.map((token) => ({
    name: token.name,
    color: token.value,
    shades: token.shades.map((shade) => ({ step: shade.step, color: shade.value })),
  }));
  const colors = colorTokens(
    palette,
    tokens.colors.some((token) => token.shades.length > 0),
    tokens.gradient ?? undefined,
  );
  const dimension = (value: number) => ({
    value: value >= 9999 ? 9999 : value / 16,
    unit: value >= 9999 ? "px" : "rem",
  });
  const t = tokens.typography;

  const document = {
    $description: `${tokens.meta.name} - generated by DesignHub on ${tokens.meta.generatedAt}`,
    ...colors,
    ...(tokens.semantic.length
      ? {
          semantic: Object.fromEntries(
            tokens.semantic.map((role) => {
              const source = tokens.colors.find((color) => color.name === role.ref);
              // Aliases only resolve to palette colors; synthesized white/black are written as values.
              const $value = source
                ? `{color.${role.ref}${source.shades.length ? ".DEFAULT" : ""}}`
                : {
                    colorSpace: "oklch",
                    components: [role.value.l, role.value.c, role.value.h],
                    hex: toHex(role.value),
                  };
              return [role.name, { $type: "color", $value }];
            }),
          ),
        }
      : {}),
    ...(t
      ? {
          font: {
            family: {
              heading: { $type: "fontFamily", $value: [t.heading.family, t.heading.category] },
              body: { $type: "fontFamily", $value: [t.body.family, t.body.category] },
            },
            weight: {
              heading: { $type: "fontWeight", $value: t.rhythm.headingWeight },
              body: { $type: "fontWeight", $value: t.rhythm.bodyWeight },
            },
            size: Object.fromEntries(
              t.steps.map((step) => [
                step.name,
                {
                  $type: "dimension",
                  $value: dimension(step.maxPx),
                  $extensions: { "dev.designhub.fluid": { min: dimension(step.minPx), css: step.clamp } },
                },
              ]),
            ),
          },
        }
      : {}),
    ...(tokens.spacing.length
      ? {
          spacing: Object.fromEntries(
            tokens.spacing.map((s) => [s.name, { $type: "dimension", $value: dimension(s.px) }]),
          ),
        }
      : {}),
    ...(tokens.radius.length
      ? {
          radius: Object.fromEntries(
            tokens.radius.map((r) => [r.name, { $type: "dimension", $value: dimension(r.px) }]),
          ),
        }
      : {}),
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

export const jsonFormat = defineFormat({
  id: "json",
  label: "JSON tokens",
  filename: "tokens.json",
  language: "json",
  generate: toJsonTokens,
});
