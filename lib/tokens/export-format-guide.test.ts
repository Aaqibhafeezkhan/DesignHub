import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, test } from "vitest";

import { fromHex } from "@/lib/color/color";
import { flatten } from "@/lib/tokens/formats";
import { roleColor } from "@/lib/tokens/native";
import { siteConfig } from "@/lib/site";
import type { ExportFormat } from "@/types/export";
import type { DesignTokens } from "@/types/tokens";

/**
 * The worked example in docs/export-formats.md, kept here so the guide's code compiles and is
 * tested. It is not registered, so it does not appear in the Export Engine.
 */

/* ---- begin guide example: generator ---- */
/** A TOML key that is always valid: quoted, so names like "spacing-0.5" are fine. */
const tomlKey = (name: string) => JSON.stringify(name);

export function toToml(tokens: DesignTokens): string {
  const prefix = tokens.meta.prefix ? `${tokens.meta.prefix}-` : "";
  const groups = new Map<string, string[]>();
  for (const token of flatten(tokens)) {
    const rows = groups.get(token.group) ?? [];
    // JSON.stringify writes a valid TOML basic string: double quotes, with backslashes escaped.
    rows.push(`${tomlKey(prefix + token.name)} = ${JSON.stringify(token.value)}`);
    groups.set(token.group, rows);
  }
  const body = [...groups].map(([group, rows]) => `[${group}]\n${rows.join("\n")}`).join("\n\n");
  return `# ${tokens.meta.name} - design tokens generated by DesignHub (${siteConfig.github})\n\n${body}\n`;
}
/* ---- end guide example: generator ---- */

/* ---- begin guide example: dark roles ---- */
/** Light and dark values for every semantic role, through the shared `roleColor` helper. */
export function tomlRoles(tokens: DesignTokens): string {
  return ["light", "dark"]
    .map((mode) => {
      const rows = tokens.semantic.flatMap((role) => {
        const resolved = roleColor(tokens, role.name, mode === "dark");
        return resolved ? [`${tomlKey(role.name)} = ${JSON.stringify(resolved.value.l.toFixed(3))}`] : [];
      });
      return `[roles.${mode}]\n${rows.join("\n")}`;
    })
    .join("\n\n");
}
/* ---- end guide example: dark roles ---- */

/* ---- begin guide example: registration ---- */
export function tomlFormat(tokens: DesignTokens): ExportFormat {
  return { id: "toml", label: "TOML", filename: "tokens.toml", language: "text", code: toToml(tokens) };
}
/* ---- end guide example: registration ---- */

const tokens = (prefix = ""): DesignTokens => ({
  meta: { name: "Acme Labs", prefix, generatedAt: "2026-01-01", colorFormat: "hex" },
  colors: [
    { name: "indigo", value: fromHex("#6366f1"), shades: [{ step: 300, value: fromHex("#a5b4fc") }] },
    { name: "slate", value: fromHex("#0f172a"), shades: [] },
  ],
  semantic: [
    { name: "primary", ref: "indigo", value: fromHex("#6366f1") },
    { name: "background", ref: "slate", value: fromHex("#ffffff") },
  ],
  gradient: null,
  typography: null,
  effects: [{ name: "shadow-md", value: '0 1px 2px rgb(0 0 0 / 0.1) "quoted"' }],
  spacing: [{ name: "0.5", px: 2 }],
  radius: [{ name: "lg", px: 12 }],
});

describe("guide example: TOML", () => {
  test("writes one table per group with quoted keys", () => {
    const toml = toToml(tokens());
    expect(toml).toContain('[color]\n"color-indigo" = "#6366f1"');
    expect(toml).toContain('[spacing]\n"spacing-0.5" = "0.125rem"');
    expect(toml).toContain('[radius]\n"radius-lg" = "0.75rem"');
  });

  test("applies the token prefix and escapes quotes in values", () => {
    const toml = toToml(tokens("acme"));
    expect(toml).toContain('"acme-color-indigo" = "#6366f1"');
    expect(toml).toContain('"acme-shadow-md" = "0 1px 2px rgb(0 0 0 / 0.1) \\"quoted\\""');
  });

  test("every non-comment line is a table header, a key and value, or blank", () => {
    for (const line of toToml(tokens()).split("\n")) {
      expect(line).toMatch(/^(#.*|\[[a-z]+\]|"[^"]+" = ".*"|)$/);
    }
  });

  test("the dark roles go through roleColor, so background and foreground swap", () => {
    const roles = tomlRoles(tokens());
    expect(roles).toContain("[roles.light]");
    expect(roles).toContain("[roles.dark]");
    expect(roleColor(tokens(), "primary", true)?.step).toBe(300);
  });

  test("the registration entry has the fields the Export Engine, the ZIP and the CLI read", () => {
    const format = tomlFormat(tokens());
    expect(format).toMatchObject({ id: "toml", filename: "tokens.toml", language: "text" });
    expect(format.code.length).toBeGreaterThan(0);
  });
});

describe("docs/export-formats.md", () => {
  const guide = readFileSync(join(process.cwd(), "docs/export-formats.md"), "utf8");
  const source = readFileSync(__filename, "utf8");

  test.each(["generator", "dark roles", "registration"])("quotes the %s example exactly as it is tested", (name) => {
    const match = source.match(
      new RegExp(
        `/\\* ---- begin guide example: ${name} ---- \\*/\\n([\\s\\S]*?)/\\* ---- end guide example: ${name} ---- \\*/`,
      ),
    );
    expect(match, name).not.toBeNull();
    expect(guide).toContain(match![1]!.trim());
  });
});
